CCC_VIDEO_CATALOG.push(...CCC_DATED_VIDEO_EDITIONS.flatMap((edition) => edition.videos));

(() => {
  const editionStyle = document.createElement('style');
  editionStyle.textContent = `
    .video-grid:has(.video-edition){display:block}.video-edition{border-top:3px solid var(--navy);margin-top:2.7rem;padding-top:1rem}.video-edition:first-child{margin-top:0}.edition-header{align-items:baseline;border-bottom:1px solid var(--line);display:flex;gap:1rem;justify-content:space-between;margin-bottom:1.25rem;padding-bottom:.72rem}.edition-header .eyebrow{margin:0;color:var(--red)}.edition-header h2{font-size:clamp(1.5rem,3vw,2.35rem);margin:0}.edition-header>p:last-child{color:#625d55;font-size:.85rem;margin:0;white-space:nowrap}.edition-cards{display:grid;grid-template-columns:repeat(3,minmax(0,1fr));gap:1.6rem 1rem}@media(max-width:760px){.edition-cards{grid-template-columns:repeat(2,minmax(0,1fr))}.edition-header{align-items:flex-start;flex-wrap:wrap}}@media(max-width:460px){.edition-cards{grid-template-columns:1fr}}`;
  document.head.append(editionStyle);

  const escapeHtml = (value) => String(value || '').replace(/[&<>'"]/g, (character) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', "'": '&#39;', '"': '&quot;' })[character]);
  const thumbnail = (film) => film.thumbnail || `https://i.ytimg.com/vi/${encodeURIComponent(film.embed)}/hqdefault.jpg`;
  const card = (film) => `<article class="video-card"><a href="VIDEO.html?id=${encodeURIComponent(film.id)}"><div class="video-thumb"><img src="${escapeHtml(thumbnail(film))}" alt="${escapeHtml(film.title)} video thumbnail" loading="lazy"><span class="play-mini">Watch</span></div><p class="eyebrow">${escapeHtml(film.category)}</p><h3>${escapeHtml(film.title)}</h3><p class="deck">Watch the video.</p></a></article>`;
  const group = (id, heading, films, label) => films.length ? `<section class="video-edition" aria-labelledby="${id}"><header class="edition-header"><p class="eyebrow">${label}</p><h2 id="${id}">${heading}</h2><p>${films.length} ${films.length === 1 ? 'video' : 'videos'}</p></header><div class="edition-cards">${films.map(card).join('')}</div></section>` : '';
  const editionId = (date) => `edition-${date.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '')}`;

  function renderDatedBrowse() {
    if (document.body.dataset.videoPage !== 'browse') return;
    const grid = document.querySelector('#video-grid');
    const filters = document.querySelector('#video-filters');
    const search = document.querySelector('#video-search');
    const summary = document.querySelector('#video-results');
    const empty = document.querySelector('#video-empty');
    if (!grid || !filters || !search || !summary || !empty) return;

    let activeCategory = 'All';
    const archive = CCC_VIDEO_CATALOG
      .filter((film) => !film.deskDate)
      .map((film) => ({ ...film, deskDate: 'August 27, 2026' }));
    const allFilms = [...CCC_DATED_VIDEO_EDITIONS.flatMap((edition) => edition.videos), ...archive];
    const categories = ['All', ...new Set(allFilms.map((film) => film.category))];
    const featured = document.querySelector('#featured-film');
    const catalogCount = document.querySelector('#catalog-count');

    if (catalogCount) catalogCount.textContent = `${allFilms.length} videos`;
    if (featured) {
      const film = CCC_DATED_VIDEO_EDITIONS[0].videos[0];
      featured.innerHTML = `<article class="lead-film"><div class="film-visual"><img src="${escapeHtml(thumbnail(film))}" alt="${escapeHtml(film.title)} video thumbnail"><a class="play-disc" href="VIDEO.html?id=${encodeURIComponent(film.id)}" aria-label="Watch ${escapeHtml(film.title)}">&#9654;</a></div><div class="lead-copy"><p class="eyebrow">CrimeNewsTV Edition · ${escapeHtml(film.category)}</p><h2>${escapeHtml(film.title)}</h2><p>${escapeHtml(film.deck)}</p><a class="watch-link" href="VIDEO.html?id=${encodeURIComponent(film.id)}">Watch the video &rarr;</a></div></article>`;
    }

    filters.innerHTML = categories.map((category) => `<button type="button" data-category="${escapeHtml(category)}" aria-pressed="${category === 'All'}">${escapeHtml(category)}</button>`).join('');
    const render = () => {
      const query = search.value.trim().toLowerCase();
      const matches = (film) => (activeCategory === 'All' || film.category === activeCategory)
        && `${film.title} ${film.category} ${film.deck}`.toLowerCase().includes(query);
      const datedGroups = CCC_DATED_VIDEO_EDITIONS.map((edition) => ({
        date: edition.date,
        films: edition.videos.filter(matches)
      }));
      const archiveMatches = archive.filter(matches);
      const total = datedGroups.reduce((sum, edition) => sum + edition.films.length, 0) + archiveMatches.length;

      grid.innerHTML = datedGroups.map((edition) => group(
        editionId(edition.date),
        edition.date,
        edition.films,
        'CrimeNewsTV Edition'
      )).join('') + group('archive-videos-heading', 'August 27, 2026', archiveMatches, 'Archive Edition');
      summary.textContent = total ? `${total} ${total === 1 ? 'video' : 'videos'} shown.` : 'No videos shown.';
      empty.hidden = Boolean(total);
    };

    filters.addEventListener('click', (event) => {
      const button = event.target.closest('button[data-category]');
      if (!button) return;
      activeCategory = button.dataset.category;
      filters.querySelectorAll('button').forEach((item) => item.setAttribute('aria-pressed', String(item === button)));
      render();
    });
    search.addEventListener('input', render);
    render();
  }

  document.addEventListener('DOMContentLoaded', () => {
    Promise.resolve(window.CCCVideoData?.hydrateCatalog?.()).finally(renderDatedBrowse);
  });
})();
